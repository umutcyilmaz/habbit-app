import { strict as assert } from "node:assert";
import { createDefaultBloomState, saveCompletedKegelSessionState, setLibraryArticleState } from "../src/storage/bloomState";
import { createBloomStatePersistenceCoordinator } from "../src/storage/bloomStatePersistence";
import { createBloomLocalStateMutationRuntime } from "../src/app/providers/bloomLocalStateMutationRuntime";
import { createBloomProductAcknowledgedActions } from "../src/app/providers/bloomProductAcknowledgedActions";
import { scoreBloomOnboarding } from "../src/domain/onboarding/scoreBloomOnboarding";
import { completedProductAnswers, productQuestions, selectProductAnswer, type DraftAnswers } from "../src/features/product-onboarding/productOnboardingQuiz";
import { getProfileReadModel, savedProfileArticles } from "../src/features/profile/profileReadModel";
import { kegelLocalDate } from "../src/features/kegel/kegelSummary";
import type { CompletedKegelSession } from "../src/domain/models/KegelState";
import { createPopulatedState } from "./verify-bloom-product-persistence";
const now = new Date(2026, 9, 13, 12);
const at = now.toISOString();
function model(state = createDefaultBloomState()) { return getProfileReadModel({durableState:state,hydrationStatus:"ready"},now)!; }
async function verify() {
  let state = createDefaultBloomState();
  const before = JSON.stringify(state);
  assert.deepEqual(model(state), {contentFreeDays:null,bestContentFreeDays:0,completedPracticeCount:0,kegelStreak:0,completedKegelSets:0,kegelRepetitions:0,completedArticleCount:0,savedArticleCount:0,completedResetCount:0,assessmentAvailable:false,assessmentDetail:"Henüz değerlendirme tamamlanmadı"});
  for (const hydrationStatus of ["loading","error"] as const) assert.equal(getProfileReadModel({durableState:state,hydrationStatus},now),null);
  assert.equal(getProfileReadModel({durableState:state,hydrationStatus:"ready"},new Date(NaN)),null);
  assert.equal(JSON.stringify(state),before,"Reading profile never changes domain state");
  const historical = createPopulatedState();
  const reset = historical.resetJourney;
  assert.equal(model(historical).completedResetCount,reset.pastAttempts.filter(attempt=>attempt.status === "completed").length + (reset.status === "completed" ? 1 : 0));
  assert.equal(model({...state,contentFree:{...state.contentFree,bestStreakSeconds:3*86400+80000}}).bestContentFreeDays,3,"Inactive retained best counts only completed 24-hour periods");
  state = setLibraryArticleState(state,"bookmark","pe",true);
  state = setLibraryArticleState(state,"completion","pe",true);
  state = setLibraryArticleState(state,"bookmark","wave",true);
  assert.deepEqual(savedProfileArticles(state).map(a=>a.id),["pe","wave"]);
  assert.equal(model(state).completedArticleCount,1);
  assert.equal(model(state).savedArticleCount,2);
  const unknown = {...state,library:{bookmarkedArticleIds:["removed","pe","pe"],completedArticleIds:["removed","pe","pe"]}};
  assert.equal(model(unknown).savedArticleCount,1,"Only existing catalog content counts; duplicates do not count twice");
  assert.equal(model(unknown).completedArticleCount,1);
  const yesterday = new Date(now); yesterday.setDate(yesterday.getDate()-1);
  const session: CompletedKegelSession = {id:"profile-kegel",status:"completed",startedAt:new Date(yesterday.getTime()-63000).toISOString(),completedAt:yesterday.toISOString(),completionDate:kegelLocalDate(yesterday),completionUtcOffsetMinutes:yesterday.getTimezoneOffset(),completedRepetitions:10,program:{configurationId:"editable-config-1",provisional:true,repetitions:10,contractionSeconds:3,relaxationSeconds:3,countdownSeconds:3,dailyTarget:3},metrics:{activeExerciseSeconds:60,elapsedSeconds:63,pausedSeconds:0,pauseCount:0}};
  state = saveCompletedKegelSessionState(state,session);
  state = saveCompletedKegelSessionState(state,session);
  assert.equal(model(state).completedKegelSets,1);
  assert.equal(model(state).kegelRepetitions,10);
  assert.equal(model(state).kegelStreak,1,"Existing yesterday grace rule is preserved");
  const startedAt = new Date(now.getTime()-2*86400000-1000).toISOString();
  state = {...state,contentFree:{...state.contentFree,status:"active",activationId:"profile-content",activatedAt:startedAt,currentStreakStartedAt:startedAt},masturbationTracking:{enabled:true,currentSession:{id:"pending",status:"awaiting_feedback",startedAt:at,endedAt:at,durationSeconds:0,pauses:[]},sessions:[{id:"completed",status:"completed",startedAt,endedAt:new Date(now.getTime()-1000).toISOString(),durationSeconds:172800,pauses:[],erectionQuality:7,usedExplicitContent:false,endingReason:"stoppedByChoice"}]}};
  assert.equal(model(state).contentFreeDays,2);
  assert.equal(model(state).bestContentFreeDays,2);
  assert.equal(model(state).completedPracticeCount,1,"Awaiting feedback is never a completed Tracking session");
  let draft:DraftAnswers = {};
  productQuestions.forEach((question,index)=>{draft=selectProductAnswer(draft,index,question.options[0]!.value);});
  const answers = completedProductAnswers(draft); assert(answers);
  const result = scoreBloomOnboarding(answers,at);
  state = {...state,productOnboarding:{status:"completed",result,planAcceptance:null}};
  assert.equal(model(state).assessmentAvailable,true);
  assert.equal(model({...state,productOnboarding:{status:"completed",result,planAcceptance:{acceptedAt:at,recommendation:result.recommendation}}}).assessmentAvailable,false,"Do not route accepted plans to the unavailable existing result screen");
  const values = new Map<string,string>();
  let fail = false;
  const persistence = createBloomStatePersistenceCoordinator({getItem:async k=>values.get(k)??null,setItem:async(k,v)=>{if(fail)throw Error("QA fail");values.set(k,v);},removeItem:async k=>{values.delete(k);},getAllKeys:async()=>[...values.keys()]},()=>now);
  await persistence.enqueueWrite(state);
  const reopened = await persistence.load(); assert(reopened.status === "success");
  assert.deepEqual(model(reopened.state),model(state),"Profile survives actual envelope round trip");
  const runtime = createBloomLocalStateMutationRuntime({initialState:reopened.state,initialHydrationStatus:"ready",persistState:persistence.enqueueWrite});
  const actions = createBloomProductAcknowledgedActions({applyAcknowledgedMutation:runtime.applyAcknowledgedMutation});
  fail = true;
  const failed = await actions.library.setArticleState("bookmark","pe",false);
  assert(!failed.ok);
  assert.equal(model(runtime.getDurableState()).savedArticleCount,2,"An accepted failed write must not change Profile");
  console.log("Profile passed: empty/unavailable, real selectors, pending exclusion, catalog filtering, idempotency, onboarding route readiness, actual persistence/restart and failed-save durable projection.");
}
void verify().catch(error=>{console.error(error);process.exitCode=1;});
